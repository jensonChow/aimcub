export type StringKey = keyof typeof STRINGS;

type Vars = Record<string, string | number>;

function interpolate(s: string, vars?: Vars): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function translate(lang: Lang, key: StringKey, vars?: Vars): string {
  const entry = STRINGS[key];
  return interpolate(entry[lang] ?? entry.en, vars);
}

const STORAGE_KEY = "aimcub.lang";

function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "zh") return saved;
    return (navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
  } catch {
    return "en";
  }
}

function persistLang(lang: Lang): void {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // ignore (private mode / no storage)
  }
}

export interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: StringKey, vars?: Vars) => string;
}

const I18nContext = createContext<I18n | null>(null);

export function useI18n(): I18n {
  const v = useContext(I18nContext);
  if (!v) throw new Error("useI18n must be used inside <I18nProvider>");
  return v;
}

export function I18nProvider(props: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);
  // The document must say which language it is actually in: `index.html` ships a static
  // lang="en", which misreports a zh session to the OS text stack, assistive tech, and CSS —
  // the `:lang(zh)` typography rules (zh titles at 500, not 600) key off this attribute.
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    persistLang(l);
  }, []);
  const t = useCallback((key: StringKey, vars?: Vars) => translate(lang, key, vars), [lang]);
  return <I18nContext.Provider value={{ lang, setLang, t }}>{props.children}</I18nContext.Provider>;
}
